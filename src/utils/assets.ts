/**
 * Резолвер изображений.
 *
 * Игра распространяется архивом: index.html + models/ + cards/ + rewards/
 * + assets/ в корне. Картинки лежат рядом обычными .jpg-файлами и грузятся
 * относительными путями — так их находит и сервер Яндекс Игр, и локальный
 * запуск из папки dist, и dev-сервер. Ведущий "/" срезается специально:
 * абсолютные пути сломались бы на поддоменах/вложенных адресах.
 *
 * Никаких data-URI в бандле нет специально: ~1.5 МБ base64 со случайными
 * сочетаниями сканер Консоли принимает за фрагменты адреса
 * сервисного хранилища («Обнаружена ссылка на сервисное хранилище»).
 */
export function A(path: string): string {
  return path.startsWith("/") ? path.slice(1) : path;
}
